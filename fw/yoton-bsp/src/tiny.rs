fn glyph(c: u8) -> Option<&'static [u8; 7]> {
    let c = c.to_ascii_uppercase();
    GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, b)| b)
}

pub fn fill_rect(fb: &mut [u16], x: usize, y: usize, w: usize, h: usize, c: u16) {
    for yy in y..(y + h).min(W) {
        for xx in x..(x + w).min(W) {
            if let Some(p) = fb.get_mut(yy * W + xx) {
                *p = c;
            }
        }
    }
}

pub fn frame_rect(fb: &mut [u16], x: usize, y: usize, w: usize, h: usize, c: u16) {
    fill_rect(fb, x, y, w, 1, c);
    fill_rect(fb, x, y + h - 1, w, 1, c);
    fill_rect(fb, x, y, 1, h, c);
    fill_rect(fb, x + w - 1, y, 1, h, c);
}

/// Draw `s` at (x, y), each font pixel `scale`² screen pixels; 6·scale
/// pixels per character. Returns the x after the text.
pub fn text(fb: &mut [u16], x: usize, y: usize, scale: usize, c: u16, s: &[u8]) -> usize {
    let mut cx = x;
    for &ch in s {
        if let Some(g) = glyph(ch) {
            for (row, bits) in g.iter().enumerate() {
                for col in 0..5 {
                    if bits & (0x10 >> col) != 0 {
                        fill_rect(fb, cx + col * scale, y + row * scale, scale, scale, c);
                    }
                }
            }
        }
        cx += 6 * scale;
    }
    cx
}

/// Decimal digits of `v` into `buf`, returns the used slice.
pub fn dec(v: u32, buf: &mut [u8; 10]) -> &[u8] {
    let mut i = buf.len();
    let mut v = v;
    loop {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
        if v == 0 || i == 0 {
            break;
        }
    }
    &buf[i..]
}

/// Eight hex digits.
pub fn hex(v: u32, buf: &mut [u8; 8]) -> &[u8] {
    for (i, b) in buf.iter_mut().enumerate() {
        let n = ((v >> (28 - 4 * i)) & 0xF) as u8;
        *b = if n < 10 { b'0' + n } else { b'A' + n - 10 };
    }
    buf
}

pub const fn rgb(r: u8, g: u8, b: u8) -> u16 {
    ((r as u16 >> 3) << 11) | ((g as u16 >> 2) << 5) | (b as u16 >> 3)
}
