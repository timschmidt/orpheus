//! Links pass 1 of the paged layout (see fw/firmware/link/) and generates
//! the toy's code and tables (`$OUT_DIR/generated.rs`): 64 functions of
//! different sizes (one larger than a page), 24 lookup tables (one larger
//! than a page), a function-pointer table. Deterministic.
use std::fmt::Write as _;

struct Rng(u32);
impl Rng {
    fn next(&mut self) -> u32 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 17;
        self.0 ^= self.0 << 5;
        self.0
    }
}

const FUNCS: usize = 64;
const BIG_FUNC: usize = 17;
/// Table lengths in words: powers of two, and one of 3072 words (12 KiB,
/// two rodata pages).
const TABLES: [usize; 24] = [
    64, 128, 256, 512, 1024, 2048, 64, 128, 256, 512, 1024, 3072, 128, 256, 512, 1024, 64, 128, 256, 512,
    1024, 256, 512, 128,
];

fn generate() -> String {
    let mut rng = Rng(0x7061_6765);
    let mut s = String::new();
    s.push_str("// Generated by build.rs; do not edit.\n");
    for (t, len) in TABLES.iter().enumerate() {
        let _ = write!(s, "pub static TABLE_{t}: [u32; {len}] = [");
        for _ in 0..*len {
            let _ = write!(s, "{:#x},", rng.next());
        }
        s.push_str("];\n");
    }
    for f in 0..FUNCS {
        let ops = if f == BIG_FUNC { 420 } else { 12 + (rng.next() % 70) as usize };
        let _ = writeln!(s, "#[inline(never)]\npub fn work_{f}(mut x: u32) -> u32 {{");
        for _ in 0..ops {
            let t = (rng.next() as usize) % TABLES.len();
            let len = TABLES[t];
            let idx = if len.is_power_of_two() {
                format!("(x as usize) & {}", len - 1)
            } else {
                format!("(x as usize) % {len}")
            };
            let _ = writeln!(
                s,
                "    x = (x ^ {:#x}).rotate_left({}).wrapping_mul({:#x});\n    x = x.wrapping_add(TABLE_{t}[{idx}]);",
                rng.next(),
                1 + rng.next() % 31,
                rng.next() | 1,
            );
        }
        s.push_str("    x\n}\n");
    }
    let _ = write!(s, "pub static WORK: [fn(u32) -> u32; {FUNCS}] = [");
    for f in 0..FUNCS {
        let _ = write!(s, "work_{f},");
    }
    s.push_str("];\n");
    s
}

fn main() {
    let dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    println!("cargo:rustc-link-search={dir}/../../firmware/link");
    println!("cargo:rustc-link-arg-bins=-Tpaged-flat.ld");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={dir}/../../firmware/link");
    let out = std::env::var("OUT_DIR").unwrap();
    std::fs::write(format!("{out}/generated.rs"), generate()).unwrap();
}
