//! Test language packs (Russian, Japanese) in the `YLN1` format of
//! `yoton_apps::strings`, built on the host. They exercise the pack
//! mechanism and give the golden images Cyrillic and CJK text; they are not
//! reviewed translations (WP UI-7 owns real language packs). Entries left
//! out fall back to English, as a partial pack would on the device.

use std::sync::OnceLock;

use yoton_apps::strings::{COUNT, Lang, Str};

/// Build a pack from (id, text) pairs.
#[must_use]
pub fn build(code: &str, name: &str, entries: &[(Str, &str)]) -> Vec<u8> {
    let mut v = b"YLN1".to_vec();
    v.extend(u16::try_from(COUNT).unwrap_or(u16::MAX).to_le_bytes());
    v.push(u8::try_from(code.len()).unwrap_or(0));
    v.push(u8::try_from(name.len()).unwrap_or(0));
    v.extend(code.as_bytes());
    v.extend(name.as_bytes());
    let mut table: Vec<u8> = Vec::new();
    let mut data: Vec<u8> = Vec::new();
    for s in Str::ALL {
        match entries.iter().find(|(id, _)| id == s) {
            Some((_, t)) => {
                table.extend(u16::try_from(data.len()).unwrap_or(0).to_le_bytes());
                table.extend(u16::try_from(t.len()).unwrap_or(0).to_le_bytes());
                data.extend(t.as_bytes());
            }
            None => table.extend([0u8; 4]),
        }
    }
    v.extend(table);
    v.extend(data);
    v
}

fn leak(v: Vec<u8>) -> &'static [u8] {
    Box::leak(v.into_boxed_slice())
}

/// The Russian test pack.
pub fn russian() -> Lang {
    static P: OnceLock<&'static [u8]> = OnceLock::new();
    Lang::from_pack(P.get_or_init(|| leak(build("ru", "Русский", RU)))).unwrap_or_default()
}

/// The Japanese test pack.
pub fn japanese() -> Lang {
    static P: OnceLock<&'static [u8]> = OnceLock::new();
    Lang::from_pack(P.get_or_init(|| leak(build("ja", "日本語", JA)))).unwrap_or_default()
}

