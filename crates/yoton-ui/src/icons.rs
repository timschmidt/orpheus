//! 1-bit icon masks, tinted by a palette role when drawn (05 §4: status icons
//! 10 × 10, row icons 12 × 12). Written as pixel art so they can be reviewed
//! in the source; the rows are packed at compile time.

/// A 1-bit mask up to 16 pixels wide; bit 15 of each row is the leftmost
/// pixel.
#[derive(Clone, Copy, Debug)]
pub struct Icon {
    pub w: u8,
    pub h: u8,
    pub rows: &'static [u16],
}

#[doc(hidden)]
#[must_use]
pub const fn row(s: &str) -> u16 {
    let b = s.as_bytes();
    assert!(b.len() <= 16);
    let mut v: u16 = 0;
    let mut i = 0;
    while i < b.len() {
        v <<= 1;
        if b[i] == b'#' {
            v |= 1;
        }
        i += 1;
    }
    if b.is_empty() { 0 } else { v << (16 - b.len()) }
}

#[doc(hidden)]
#[must_use]
pub const fn width(rows: &[&str]) -> u8 {
    let mut w = 0;
    let mut i = 0;
    while i < rows.len() {
        if rows[i].len() > w {
            w = rows[i].len();
        }
        i += 1;
    }
    assert!(w <= 16);
    w as u8
}

macro_rules! icon {
    ($name:ident, $doc:literal, [$($r:literal),* $(,)?]) => {
        #[doc = $doc]
        pub const $name: Icon = Icon {
            w: width(&[$($r),*]),
            h: [$($r),*].len() as u8,
            rows: &[$(row($r)),*],
        };
    };
}

