#!/usr/bin/env python3
"""Generate src/tables.rs for yoton-fs.

Inputs (both are data, not code):
  * Unicode CaseFolding.txt (status C and S = simple case folding), BMP only.
    Default path: /usr/share/unicode/ucd/CaseFolding.txt (Fedora unicode-ucd).
  * The exFAT recommended up-case table (exFAT specification section 7.2.5),
    taken from a fresh `mkfs.exfat` image and decompressed.
  * Code page 437 (upper half) from Python's codec, for FAT short names.

Run from the crate directory:  python3 tools/gen_tables.py > src/tables.rs
"""
import os
import struct
import subprocess
import sys
import tempfile

CASEFOLDING = os.environ.get("CASEFOLDING", "/usr/share/unicode/ucd/CaseFolding.txt")


def fold_map():
    m = {}
    version = "?"
    with open(CASEFOLDING, encoding="utf-8") as f:
        for line in f:
            if line.startswith("# CaseFolding-"):
                version = line[2:].strip()
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            code, status, mapping = [x.strip() for x in line.split(";")[:3]]
            if status not in ("C", "S"):
                continue
            c = int(code, 16)
            t = int(mapping, 16)
            if c > 0xFFFF or t > 0xFFFF:
                continue
            m[c] = t
    return m, version


def upcase_map():
    with tempfile.TemporaryDirectory() as d:
        img = os.path.join(d, "x.img")
        with open(img, "wb") as f:
            f.truncate(64 * 1024 * 1024)
        subprocess.run(["mkfs.exfat", "-q", img], check=True, stdout=subprocess.DEVNULL)
        data = open(img, "rb").read()
    bs = data[:512]
    fat_off = struct.unpack_from("<I", bs, 80)[0]
    heap_off = struct.unpack_from("<I", bs, 88)[0]
    root = struct.unpack_from("<I", bs, 96)[0]
    spc = 1 << bs[109]
    cl = lambda c: (heap_off + (c - 2) * spc) * 512
    # walk the root directory's first cluster (good enough for a fresh volume)
    off = cl(root)
    table = None
    for i in range(spc * 16):
        e = data[off + i * 32: off + i * 32 + 32]
        if e[0] == 0x82:
            csum = struct.unpack_from("<I", e, 4)[0]
            first = struct.unpack_from("<I", e, 20)[0]
            length = struct.unpack_from("<Q", e, 24)[0]
            table = data[cl(first): cl(first) + length]
            break
        if e[0] == 0:
            break
    assert table is not None
    # checksum per spec
    s = 0
    for b in table:
        s = (((s & 1) << 31) | (s >> 1)) + b
        s &= 0xFFFFFFFF
    assert s == csum, (hex(s), hex(csum))
    # decompress
    units = struct.unpack("<%dH" % (len(table) // 2), table)
    m = {}
    c = 0
    i = 0
    while i < len(units) and c < 0x10000:
        u = units[i]
        if u == 0xFFFF and i + 1 < len(units):
            c += units[i + 1]
            i += 2
            continue
        if u != c:
            m[c] = u
        c += 1
        i += 1
    return m, csum, len(table)


def runs(m):
    """Encode {cp: target} as (start, count, delta, step) runs, step 1 or 2."""
    keys = sorted(m)
    out = []
    i = 0
    while i < len(keys):
        s = keys[i]
        d = (m[s] - s) & 0xFFFF
        best = (1, 1)
        for step in (1, 2):
            n = 1
            while True:
                c = s + n * step
                if c in m and ((m[c] - c) & 0xFFFF) == d and (i + n < len(keys)) and keys[i + n] == c:
                    n += 1
                else:
                    break
            if n > best[0]:
                best = (n, step)
        n, step = best
        out.append((s, n, d, step))
        i += n
    # verify
    chk = {}
    for s, n, d, step in out:
        for k in range(n):
            c = s + k * step
            chk[c] = (c + d) & 0xFFFF
    assert chk == m
    return out


def emit(name, rs, doc):
    print(doc)
    print("pub(crate) static %s: [Run; %d] = [" % (name, len(rs)))
    for s, n, d, step in rs:
        print("    Run { start: 0x%04X, count: %d, delta: 0x%04X, step: %d }," % (s, n, d, step))
    print("];")
    print()


def main():
    fm, ver = fold_map()
    um, csum, size = upcase_map()
    fr = runs(fm)
    ur = runs(um)
    cp = bytes(range(128, 256)).decode("cp437")
    print("// @generated by tools/gen_tables.py -- do not edit by hand.")
    print("//")
    print("// Data sources: Unicode %s (status C+S, BMP only; Unicode licence," % ver)
    print("// data files), the exFAT recommended up-case table (exFAT specification")
    print("// 7.2.5, read back from a mkfs.exfat image and checksum-verified), and")
    print("// code page 437 (upper half).")
    print()
    print("/// A run of code points mapped by adding `delta` (wrapping): code points")
    print("/// `start, start + step, ...`, `count` of them.")
    print("#[derive(Clone, Copy)]")
    print("pub(crate) struct Run {")
    print("    pub start: u16,")
    print("    pub count: u16,")
    print("    pub delta: u16,")
    print("    pub step: u8,")
    print("}")
    print()
    emit("FOLD", fr, "/// Unicode simple case folding (C + S), BMP.")
    emit("UPCASE", ur, "/// exFAT recommended up-case table, as differences from identity.")
    print("/// Checksum of the recommended up-case table as stored by mkfs.exfat.")
    print("pub(crate) const STD_UPCASE_CHECKSUM: u32 = 0x%08X;" % csum)
    print("/// Byte length of that stored table.")
    print("pub(crate) const STD_UPCASE_LEN: u64 = %d;" % size)
    print()
    print("/// Code page 437, bytes 0x80..=0xFF.")
    print("pub(crate) static CP437_HIGH: [u16; 128] = [")
    for i in range(0, 128, 8):
        print("    " + " ".join("0x%04X," % ord(ch) for ch in cp[i:i + 8]))
    print("];")


if __name__ == "__main__":
    sys.exit(main())
